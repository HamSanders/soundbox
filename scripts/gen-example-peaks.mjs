#!/usr/bin/env node
/**
 * Draws the waveform each hero card shows: one row of peaks per file under
 * `site/public/examples/`, written to `app/src/content/example-peaks.ts`.
 *
 * Each file is decoded to mono with ffmpeg and cut into BARS equal slices; a
 * slice keeps its loudest sample (a mean would flatten the transient that
 * makes an impact look like one), and the row is scaled so its loudest slice
 * is 100. Run it again whenever a file in that folder is added or re-rendered:
 *
 *   node scripts/gen-example-peaks.mjs
 *
 * Needs ffmpeg on PATH. Nothing in the build or the tests runs this.
 */

import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const BARS = 64;
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "site", "public", "examples");
const out = join(root, "app", "src", "content", "example-peaks.ts");

function peaksOf(file) {
  const raw = execFileSync(
    "ffmpeg",
    ["-v", "error", "-i", file, "-ac", "1", "-ar", "8000", "-f", "f32le", "-"],
    { maxBuffer: 256 * 1024 * 1024 },
  );
  const samples = new Float32Array(raw.buffer, raw.byteOffset, Math.floor(raw.byteLength / 4));
  const step = samples.length / BARS;
  const bars = [];
  let max = 0;
  for (let i = 0; i < BARS; i++) {
    let m = 0;
    const end = Math.min(samples.length, Math.floor((i + 1) * step));
    for (let j = Math.floor(i * step); j < end; j++) m = Math.max(m, Math.abs(samples[j]));
    bars.push(m);
    max = Math.max(max, m);
  }
  return bars.map((v) => (max > 0 ? Math.round((v / max) * 100) : 0));
}

const files = readdirSync(dir).filter((f) => f.endsWith(".mp3")).sort();
const rows = files.map((f) => `  "${f.replace(/\.mp3$/, "")}": [${peaksOf(join(dir, f)).join(", ")}],`);

writeFileSync(
  out,
  `/**
 * Generated by \`scripts/gen-example-peaks.mjs\`; do not edit by hand.
 *
 * ${BARS} peaks per render in \`site/public/examples/\`, each 0 to 100 with the
 * loudest slice of the file at 100. The hero cards draw these as bars.
 */

export const EXAMPLE_PEAKS: Record<string, readonly number[]> = {
${rows.join("\n")}
};
`,
);
console.log(`${files.length} files -> ${out}`);
